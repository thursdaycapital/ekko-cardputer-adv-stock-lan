"""Generate small read-only emoji property ranges from pinned Unicode data."""
import argparse
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def load_properties():
    manifest = json.loads((HERE / "sources.json").read_text())
    for name, info in manifest["files"].items():
        if hashlib.sha256((HERE / "upstream" / name).read_bytes()).hexdigest() != info["sha256"]:
            raise ValueError(f"Pinned Unicode source changed: {name}")
    result = {}
    for line in (HERE / "upstream/emoji-data.txt").read_text().splitlines():
        record = line.split("#", 1)[0].strip()
        if not record:
            continue
        interval, property_name = (part.strip() for part in record.split(";"))
        ends = interval.split("..")
        first, last = int(ends[0], 16), int(ends[-1], 16)
        result.setdefault(property_name, set()).update(range(first, last + 1))
    return result


def ranges(values):
    result = []
    for value in sorted(values):
        if result and value == result[-1][1] + 1:
            result[-1][1] = value
        else:
            result.append([value, value])
    return result


def generate():
    properties = load_properties()
    selected = {
        "emojiPresentation": properties["Emoji_Presentation"],
        "emojiModifier": properties["Emoji_Modifier"],
        "emojiJoinerBase": properties["Emoji"] - set(range(128)) - properties["Emoji_Modifier"],
        # Emoji tags form flag sequences. Do not remove Emoji_Component as a
        # whole: that property also includes ASCII #/*/digits and flag bases.
        "emojiTag": properties["Emoji_Component"] & set(range(0xE0020, 0xE0080)),
    }
    text = """// Generated by assets/chat-symbols/generate.py. Do not edit.
// Derived from Unicode 17.0.0 emoji-data.txt; Unicode-3.0 license.
// See upstream/LICENSE.txt, sources.json and NOTICE.
#pragma once
#include <cstddef>
#include <cstdint>
namespace native_chat_symbols_detail {
struct Range { uint32_t first, last; };
template <size_t N>
inline bool inRanges(uint32_t value, const Range (&ranges)[N]) {
  size_t lower = 0, upper = N;
  while (lower < upper) {
    const size_t middle = lower + (upper - lower) / 2;
    if (value < ranges[middle].first) upper = middle;
    else if (value > ranges[middle].last) lower = middle + 1;
    else return true;
  }
  return false;
}
"""
    counts = {}
    for name, values in selected.items():
        intervals = ranges(values)
        text += f"inline bool {name}(uint32_t value) {{\n  static const Range ranges[] = {{\n"
        text += "".join(f"    {{0x{first:X}, 0x{last:X}}},\n" for first, last in intervals)
        text += "  };\n  return inRanges(value, ranges);\n}\n"
        counts[name] = {"codepoints": len(values), "ranges": len(intervals), "data_bytes": len(intervals) * 8}
    text += "}  // namespace native_chat_symbols_detail\n"
    generated = {
        "schema_version": 1,
        "unicode_version": "17.0.0",
        "header_sha256": hashlib.sha256(text.encode()).hexdigest(),
        "properties": counts,
        "range_data_bytes": sum(info["data_bytes"] for info in counts.values()),
    }
    return {"ChatSymbolRanges.h": text.encode(),
            "manifest.json": (json.dumps(generated, indent=2) + "\n").encode()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    for name, data in generate().items():
        path = HERE / name
        if options.check:
            if not path.is_file() or path.read_bytes() != data:
                raise SystemExit(f"Unicode range output is stale: {name}")
        else:
            path.write_bytes(data)
    print("Unicode source hashes and deterministic ranges verified" if options.check else "Unicode ranges generated")


if __name__ == "__main__":
    main()
