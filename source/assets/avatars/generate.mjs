#!/usr/bin/env node
// Offline conversion of the checked-in brand assets. npm ci installs pinned sharp.
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'
import sharp from 'sharp'

const base = path.dirname(fileURLToPath(import.meta.url))
const firmware = path.resolve(base, '../..')
const manifest = JSON.parse(await fs.readFile(path.join(base, 'manifest.json'), 'utf8'))
const catalog = JSON.parse(await fs.readFile(path.join(firmware, 'config/agents.json'), 'utf8')).agents
const check = process.argv.includes('--check')
if (process.argv.some(arg => arg.startsWith('--') && arg !== '--check')) throw new Error('Usage: node generate.mjs [--check]')
if (JSON.stringify(manifest.assets.map(a => a.id)) !== JSON.stringify(catalog.map(a => a.id))) throw new Error('Canonical agent order mismatch')
const { width, height, padding } = manifest
if (![width, height, padding].every(Number.isSafeInteger) || width < 1 || height < 1 || padding < 0 || 2 * padding >= Math.min(width, height)) throw new Error('Invalid avatar dimensions')
const background565 = Number(manifest.background_rgb565)
const background = {
  r: Math.round(((background565 >> 11) & 31) * 255 / 31),
  g: Math.round(((background565 >> 5) & 63) * 255 / 63),
  b: Math.round((background565 & 31) * 255 / 31), alpha: 1,
}
const digest = data => createHash('sha256').update(data).digest('hex')
const arrays = []
const tiles = []
for (const asset of manifest.assets) {
  const source = path.resolve(base, asset.file)
  if (!source.startsWith(`${base}${path.sep}`)) throw new Error('Asset path escapes asset directory')
  const bytes = await fs.readFile(source)
  if (digest(bytes) !== asset.sha256) throw new Error(`${asset.id}: original source checksum mismatch`)
  // The header retains the download digest when published PNG metadata was stripped.
  // The actual checked-in bytes are always verified against sha256 above.
  const originalDigest = asset.downloaded_source_sha256 ?? asset.sha256
  if (!/^[a-f0-9]{64}$/.test(originalDigest)) throw new Error(`${asset.id}: invalid original source checksum`)
  if (asset.original_format === 'svg' && /<image\b|data:image|<script\b|(?:href|src)=["']https?:/i.test(bytes.toString())) throw new Error(`${asset.id}: SVG must be standalone vector artwork`)
  // Trim only transparent external padding, preserving opaque brand backgrounds.
  const raw = await sharp(bytes, { density: 144 }).resize(512, 512, { fit: 'inside' }).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
  let left = raw.info.width, top = raw.info.height, right = -1, bottom = -1
  for (let y = 0; y < raw.info.height; y++) for (let x = 0; x < raw.info.width; x++) {
    if (raw.data[(y * raw.info.width + x) * 4 + 3] === 0) continue
    left = Math.min(left, x); right = Math.max(right, x); top = Math.min(top, y); bottom = Math.max(bottom, y)
  }
  if (right < left || bottom < top) throw new Error(`${asset.id}: empty artwork`)
  const inner = await sharp(raw.data, { raw: raw.info }).extract({ left, top, width: right - left + 1, height: bottom - top + 1 })
    .resize(width - padding * 2, height - padding * 2, { fit: 'contain', background }).flatten({ background }).removeAlpha()
    .extend({ top: padding, bottom: padding, left: padding, right: padding, background }).raw().toBuffer()
  const values = []
  const binary = Buffer.alloc(width * height * 2)
  for (let i = 0; i < width * height; i++) {
    const value = ((inner[3 * i] >> 3) << 11) | ((inner[3 * i + 1] >> 2) << 5) | (inner[3 * i + 2] >> 3)
    values.push(`0x${value.toString(16).padStart(4, '0')}`)
    binary.writeUInt16LE(value, i * 2)
  }
  const name = `kAgentAvatar_${asset.id.replaceAll('-', '_')}`
  const rows = Array.from({ length: Math.ceil(values.length / 16) }, (_, i) => `  ${values.slice(i * 16, i * 16 + 16).join(', ')},`)
  arrays.push(`// ${asset.id}: original ${originalDigest}; pixels ${digest(binary)}\nstatic const uint16_t ${name}[] PROGMEM = {\n${rows.join('\n')}\n};`)
  tiles.push({ id: asset.id, name, pixels_sha256_le: digest(binary), buffer: inner })
}
const header = `// Generated by assets/avatars/generate.mjs. Do not edit pixel data.\n// RGB565 native uint16_t values; no byte swap. Original brand assets and attribution: assets/avatars/manifest.json.\n#pragma once\n#include <stddef.h>\n#include <stdint.h>\n#if defined(ARDUINO)\n#include <pgmspace.h>\n#elif !defined(PROGMEM)\n#define PROGMEM\n#endif\n\nstruct AgentAvatarAsset { const uint16_t* pixels; uint16_t width, height; };\n\n${arrays.join('\n\n')}\n\nstatic const AgentAvatarAsset kAgentAvatars[] = {\n${tiles.map(t => `  { ${t.name}, ${width}, ${height} }, // ${t.id}`).join('\n')}\n};\nstatic constexpr size_t kAgentAvatarCount = sizeof(kAgentAvatars) / sizeof(kAgentAvatars[0]);\ninline const AgentAvatarAsset* nativeAgentLogo(size_t index) {\n  return index < kAgentAvatarCount ? &kAgentAvatars[index] : nullptr;\n}\n`
const headerPath = path.join(firmware, 'include/AgentAvatarAssets.h')
const summary = JSON.stringify({ generator: 'sharp', sharp_version: sharp.versions.sharp, width, height, background_rgb565: manifest.background_rgb565,
  header_sha256: digest(header), assets: tiles.map(({ id, pixels_sha256_le }) => ({ id, pixels_sha256_le })) }, null, 2) + '\n'
if (check) {
  if (await fs.readFile(headerPath, 'utf8') !== header) throw new Error('Generated header is stale')
  if (await fs.readFile(path.join(base, 'generated.json'), 'utf8') !== summary) throw new Error('Generated pixel manifest is stale')
} else {
  await fs.writeFile(headerPath, header)
  await fs.writeFile(path.join(base, 'generated.json'), summary)
  await fs.mkdir(path.join(base, 'previews'), { recursive: true })
  await Promise.all(tiles.map(t => sharp(t.buffer, { raw: { width, height, channels: 3 } }).png().toFile(path.join(base, 'previews', `${t.id}.png`))))
  const escape = value => value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;')
  const labels = `<svg width="640" height="600" xmlns="http://www.w3.org/2000/svg"><g fill="#193029" font-family="sans-serif" font-size="12">${manifest.assets.map((a, i) => `<text x="${i % 4 * 160 + 8}" y="${Math.floor(i / 4) * 150 + 120}">${escape(a.name)}</text><text x="${i % 4 * 160 + 8}" y="${Math.floor(i / 4) * 150 + 138}" font-size="10">${a.original_format} / ${a.source_kind.startsWith('first_party') ? 'product owner' : 'Ekko upstream'}</text>`).join('')}</g></svg>`
  const composite = await Promise.all(tiles.map(async (t, i) => ({
    input: await sharp(t.buffer, { raw: { width, height, channels: 3 } }).resize(width * 2, height * 2, { kernel: 'nearest' }).png().toBuffer(),
    left: i % 4 * 160 + 36, top: Math.floor(i / 4) * 150 + 12,
  })))
  await sharp({ create: { width: 640, height: 600, channels: 3, background } }).composite([...composite, { input: Buffer.from(labels) }])
    .png().toFile(path.join(base, 'previews/contact-sheet.png'))
}
console.log(`${check ? 'Verified' : 'Generated'} ${tiles.length} real brand avatars, ${width}x${height}, ${tiles.length * width * height * 2} bytes in flash`)
